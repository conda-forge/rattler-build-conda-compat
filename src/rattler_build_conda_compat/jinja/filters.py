from __future__ import annotations

import datetime
import time
from zoneinfo import ZoneInfo

from rattler_build_conda_compat.jinja.utils import _MissingUndefined


def _version_to_build_string(some_string: str | _MissingUndefined) -> str:
    """
    Converts some version by removing the . character and returning only the first two elements of the version.
    If piped value is undefined, it returns the undefined value as is.
    """
    if isinstance(some_string, _MissingUndefined):
        return f"{some_string._undefined_name}_version_to_build_string"  # noqa: SLF001
    # We first split the string by whitespace and take the first part
    split = some_string.split()[0] if some_string.split() else some_string
    # We then split the string by . and take the first two parts
    parts = split.split(".")
    major = parts[0] if len(parts) > 0 else ""
    minor = parts[1] if len(parts) > 1 else ""
    return f"{major}{minor}"


def _bool(value: str) -> bool:
    return bool(value)


def _split(s: str, sep: str | None = None) -> list[str]:
    """Filter that split a string by a separator"""
    return s.split(sep)


def _now() -> float:
    """Function giving the current unix timestamp"""
    return time.time()


def _datetimeformat(
    timestamp: float | str,
    *,
    format: str,  # noqa: A002
    tz: str | None = None,
) -> str:
    """Filter to format a timestamp."""

    if isinstance(timestamp, str):
        ts = datetime.datetime.fromisoformat(timestamp)
        if tz is not None:
            ts = ts.replace(tzinfo=ZoneInfo(tz))
    else:
        ts = datetime.datetime.fromtimestamp(timestamp, tz=datetime.UTC)

    # code generated by AI to handle pre-canned minijinja formats
    # see https://docs.rs/minijinja-contrib/latest/minijinja_contrib/filters/fn.datetimeformat.html
    if format == "short":
        format = "%Y-%m-%d %H:%M"  # noqa: A001
    elif format == "medium":
        format = "%b %d %Y %H:%M"  # noqa: A001
    elif format == "long":
        format = "%B %d %Y %H:%M:%S"  # noqa: A001
    elif format == "full":
        return f"{ts.strftime('%A, %B %d %Y %H:%M:%S')}.{int(ts.microsecond / 100000)}"
    elif format == "unix":
        return str(int(ts.timestamp()))
    elif format == "iso":
        return ts.isoformat()

    return ts.strftime(format)
